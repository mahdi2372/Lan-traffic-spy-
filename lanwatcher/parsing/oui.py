class OuiLookup:
    """Offline OUI -> vendor lookup with optional IEEE oui.txt enrichment."""

    def __init__(self, extra_path: Optional[Path] = None):
        self._table: dict = dict(BUILTIN_OUI)
        self._loaded_file = False
        if extra_path and Path(extra_path).exists():
            self.load_ieee_file(Path(extra_path))

    def load_ieee_file(self, path: Path) -> int:
        """Load IEEE 'MA-L' oui.txt ('AA-BB-CC   (hex)		Vendor')."""
        added = 0
        try:
            for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
                if "(hex)" not in line.lower() and "(base 16)" not in line.lower():
                    continue
                parts = line.split(None, 2)
                if len(parts) < 3:
                    continue
                raw_prefix = parts[0].strip().lower().replace(":", "").replace("-", "").replace(".", "")
                prefix = raw_prefix if len(raw_prefix) == 6 and all(c in "0123456789abcdef" for c in raw_prefix) else None
                if not prefix:
                    continue
                vendor = parts[2].strip().strip("()").strip()
                if prefix not in self._table:
                    added += 1
                self._table[prefix] = vendor
            self._loaded_file = True
        except OSError:
            return added
        return added

    def vendor(self, mac_norm: Optional[str]) -> Optional[str]:
        if not mac_norm or len(mac_norm) < 6:
            return None
        p6 = mac_norm[:6].lower()
        if p6 in self._table:
            return self._table[p6]
        # locally-administered bit -> virtual/randomized address
        try:
            if int(p6[1], 16) & 0x2:
                return "Locally administered (virtual/randomized)"
        except ValueError:
            return None
        return None

    def __len__(self) -> int:
        return len(self._table)
